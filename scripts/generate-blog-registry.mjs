import fs from "fs";
import path from "path";
import { fileURLToPath } from "url";

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const blogDir = path.join(__dirname, "..", "content", "blog");

const DEFAULT_IMAGE = "https://images.unsplash.com/photo-1516321318423-f06f85e504b3?w=800&q=80";

// Normaliza chaves do frontmatter: inglês → português
const KEY_MAP = {
  title: "titulo",
  description: "descricao",
  date: "data",
  image: "imagem",
};

const files = fs.readdirSync(blogDir).filter((f) => f.endsWith(".mdx"));
const entries = files.map((file) => {
  const raw = fs.readFileSync(path.join(blogDir, file), "utf-8");
  const match = raw.match(/^---\r?\n([\s\S]*?)\r?\n---\r?\n?([\s\S]*)$/);
  const data = {};
  let content = "";
  if (match) {
    match[1].split("\n").forEach((line) => {
      const idx = line.indexOf(":");
      if (idx === -1) return;
      let key = line.slice(0, idx).trim();
      let val = line.slice(idx + 1).trim();
      val = val.replace(/^"(.*)"$/, "$1").replace(/^'(.*)'$/, "$1");
      // Normalizar: inglês → português
      if (KEY_MAP[key]) key = KEY_MAP[key];
      if (key === "tags") {
        try {
          data[key] = JSON.parse(val.replace(/'/g, '"'));
        } catch { data[key] = []; }
      } else {
        const num = Number(val);
        data[key] = !isNaN(num) && val !== "" ? num : val;
      }
    });
    content = match[2] || "";
  }
  // Validar título: se não existe frontmatter ou título vazio, pular o post
  const titulo = data.titulo ? String(data.titulo).trim() : "";
  if (!titulo) return null;

  // Validar data: se ausente ou inválida, pular o post
  const dataStr = data.data ? String(data.data).trim() : "";
  const dataValida = dataStr ? !isNaN(new Date(dataStr + "T12:00:00").getTime()) : false;
  if (!dataValida) return null;

  return {
    imagem: data.imagem || DEFAULT_IMAGE,
    titulo,
    slug: data.slug || file.replace(".mdx", ""),
    descricao: data.descricao?.trim() || "",
    data: dataStr,
    tags: Array.isArray(data.tags) ? data.tags : [],
    content,
  };
}).filter(Boolean).sort((a, b) => {
  return b.data.localeCompare(a.data);
});

const ts = `// GENERATED BY scripts/generate-blog-registry.mjs

export type BlogPost = {
  titulo: string;
  slug: string;
  imagem: string;
  descricao: string;
  data: string;
  tags: string[];
  content: string;
};

export const blogRegistry: BlogPost[] = ${JSON.stringify(entries, null, 2)};
`;

fs.writeFileSync(path.join(__dirname, "..", "lib", "blog-data.ts"), ts, "utf-8");
console.log(`✅ lib/blog-data.ts gerado com ${entries.length} posts`);
